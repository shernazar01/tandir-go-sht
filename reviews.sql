create table if not exists public.customer_reviews (
  id bigint generated by default as identity primary key,
  name varchar(60) not null,
  text varchar(600) not null,
  rating smallint not null check (rating between 1 and 5),
  created_at timestamptz not null default now()
);

create index if not exists customer_reviews_created_at_idx
  on public.customer_reviews (created_at desc);

-- Jadvalga brauzerdan to‘g‘ridan-to‘g‘ri kirish yopiq.
-- Faqat serverdagi maxfiy service_role kaliti orqali API yozadi va o‘qiydi.
alter table public.customer_reviews enable row level security;
grant all on table public.customer_reviews to service_role;
grant usage, select on sequence public.customer_reviews_id_seq to service_role;

grant usage on schema public to service_role;
